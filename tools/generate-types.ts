/**
 * Generates TypeScript types from the official Keycloak Admin REST API OpenAPI spec.
 *
 * Usage: KEYCLOAK_VERSION=26.8.1 npm run gen:types
 */
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import openapiTS, { astToString } from 'openapi-typescript';

const version = process.env.KEYCLOAK_VERSION || '26.8.1';
const specUrl = `https://www.keycloak.org/docs-api/${version}/rest-api/openapi.json`;
const output = resolve(__dirname, '..', 'lib', 'generated', 'keycloak-admin.ts');

async function main(): Promise<void> {
  const ast = await openapiTS(new URL(specUrl));
  const header = [
    '/* eslint-disable */',
    `// Generated by tools/generate-types.ts from ${specUrl}`,
    '// Do not edit by hand. Run `npm run gen:types` to regenerate.',
    `export const KEYCLOAK_SPEC_VERSION = '${version}';`,
    '',
  ].join('\n');
  writeFileSync(output, header + astToString(ast));
  console.log(`Types for Keycloak ${version} written to ${output}`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
